type fixture struct {
	t    *testing.T
	h    *rules.Host
	cmds map[string]string
}

func newFixture(t *testing.T) *fixture {
	t.Helper()
	fx := &fixture{t: t, cmds: map[string]string{}}
	fx.h = &rules.Host{Root: t.TempDir()}
	fx.h.Exec = func(ctx context.Context, name string, args ...string) (string, error) {
		if out, ok := fx.cmds[strings.TrimSpace(name+" "+strings.Join(args, " "))]; ok {
			return out, nil
		}
		return "", errors.New(name + ": not found (fixture)")
	}
	return fx
}

func (fx *fixture) file(p, content string) *fixture {
	fx.t.Helper()
	return fx.bytes(p, []byte(content))
}

func (fx *fixture) bytes(p string, b []byte) *fixture {
	fx.t.Helper()
	local := fx.h.P(p)
	if err := os.MkdirAll(filepath.Dir(local), 0o755); err != nil {
		fx.t.Fatal(err)
	}
	if err := os.WriteFile(local, b, 0o644); err != nil {
		fx.t.Fatal(err)
	}
	return fx
}

func (fx *fixture) collect(opts Options) Result {
	fx.t.Helper()
	opts.NoBinaries = opts.NoBinaries || runtime.GOOS == "windows"
	return CollectResult(context.Background(), fx.h, opts)
}

// has finds a component by ecosystem/name/version.
func has(comps []Component, eco, name, ver string) (Component, bool) {
	for _, c := range comps {
		if c.Ecosystem == eco && c.Name == name && c.Version == ver {
			return c, true
		}
	}
	return Component{}, false
}

func mustHave(t *testing.T, comps []Component, eco, name, ver string) Component {
	t.Helper()
	c, ok := has(comps, eco, name, ver)
	if !ok {
		t.Fatalf("missing %s %s@%s in %v", eco, name, ver, names(comps))
	}
	return c
}

func names(comps []Component) []string {
	var out []string
	for _, c := range comps {
		out = append(out, c.Ecosystem+"/"+c.Name+"@"+c.Version)
	}
	sort.Strings(out)
	return out
}

