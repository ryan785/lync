func TestSitePackages(t *testing.T) {
	fx := newFixture(t)
	sp := "/usr/local/lib/python3.11/site-packages"
	fx.file(sp+"/urllib3-1.24.1.dist-info/METADATA", "Metadata-Version: 2.1\nName: urllib3\nVersion: 1.24.1\n\nLong description Version: 9\n")
	fx.file(sp+"/urllib3-1.24.1.dist-info/INSTALLER", "pip\n")
	fx.file(sp+"/Old_Pkg-0.9.egg-info", "Metadata-Version: 1.0\nName: Old_Pkg\nVersion: 0.9\n")
	fx.file(sp+"/urllib3/__init__.py", "")
	// RHEL: rpm-owned module under /usr/lib, kept out by default.
	rp := "/usr/lib/python3.9/site-packages"
	fx.file(rp+"/requests-2.25.1.dist-info/METADATA", "Name: requests\nVersion: 2.25.1\n")
	fx.file(rp+"/requests-2.25.1.dist-info/INSTALLER", "rpm\n")
	fx.file(rp+"/six-1.15.0-py3.9.egg-info/PKG-INFO", "Name: six\nVersion: 1.15.0\n")
	fx.file(rp+"/flask-2.0.0.dist-info/METADATA", "Name: Flask\nVersion: 2.0.0\n")
	fx.file(rp+"/flask-2.0.0.dist-info/INSTALLER", "pip\n")
	// a venv inside an app root
	fx.file("/srv/app/venv/lib/python3.11/site-packages/jinja2-2.10.dist-info/METADATA", "Name: Jinja2\nVersion: 2.10\n")

	r := fx.collect(Options{})
	c := mustHave(t, r.Components, EcoPyPI, "urllib3", "1.24.1")
	if c.Scope != ScopeSystem || c.Source != SourceMetadata || c.Paths[0] != sp+"/urllib3-1.24.1.dist-info" {
		t.Errorf("urllib3: %+v", c)
	}
	mustHave(t, r.Components, EcoPyPI, "old-pkg", "0.9")
	mustHave(t, r.Components, EcoPyPI, "flask", "2.0.0")
	if c := mustHave(t, r.Components, EcoPyPI, "jinja2", "2.10"); c.Scope != ScopeApp {
		t.Errorf("venv scope = %s", c.Scope)
	}
	if _, ok := has(r.Components, EcoPyPI, "requests", "2.25.1"); ok {
		t.Error("rpm-installed module must be skipped by default")
	}
	if _, ok := has(r.Components, EcoPyPI, "six", "1.15.0"); ok {
		t.Error("installer-less egg-info under /usr/lib must be skipped by default")
	}
	r = fx.collect(Options{IncludeOSManaged: true})
	mustHave(t, r.Components, EcoPyPI, "requests", "2.25.1")
}

