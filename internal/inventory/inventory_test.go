func TestSplitImageRef(t *testing.T) {
	for in, want := range map[string]string{
		"nginx:1.19":                       "nginx|1.19",
		"registry.local:5000/team/app:2.0": "registry.local:5000/team/app|2.0",
		"registry.local:5000/team/app":     "registry.local:5000/team/app|",
		"ghcr.io/org/app@sha256:abcd":      "ghcr.io/org/app|",
		"ghcr.io/org/app:1.0@sha256:abcd":  "ghcr.io/org/app|1.0",
	} {
		n, tag := splitImageRef(in)
		if n+"|"+tag != want {
			t.Errorf("%s: got %s|%s", in, n, tag)
		}
	}
}
