func TestNPMLock(t *testing.T) {
	v1, err := parseNPMLock([]byte(npmLockV1))
	if err != nil {
		t.Fatal(err)
	}
	mustHave(t, v1, EcoNPM, "lodash", "4.17.15")
	if c := mustHave(t, v1, EcoNPM, "minimist", "0.0.8"); !c.Dev {
		t.Error("nested v1 dev dep not flagged dev")
	}
	if len(v1) != 3 {
		t.Errorf("v1: want 3 comps (file: dep skipped), got %v", names(v1))
	}
	v3, err := parseNPMLock([]byte(npmLockV3))
	if err != nil {
		t.Fatal(err)
	}
	mustHave(t, v3, EcoNPM, "express", "4.17.1")
	mustHave(t, v3, EcoNPM, "qs", "6.7.0")
	if c := mustHave(t, v3, EcoNPM, "@babel/core", "7.12.0"); !c.Dev {
		t.Error("v3 dev flag lost")
	}
	if len(v3) != 3 {
		t.Errorf("v3: root and links must be skipped, got %v", names(v3))
	}
}

