func TestDedupe(t *testing.T) {
	in := []Component{
		{Ecosystem: EcoNPM, Name: "lodash", Version: "4.17.15", Paths: []string{"/srv/b/package-lock.json"}, Scope: ScopeSystem, Dev: true},
		{Ecosystem: EcoNPM, Name: "lodash", Version: "4.17.15", Paths: []string{"/srv/a/package-lock.json"}, Scope: ScopeApp},
		{Ecosystem: EcoNPM, Name: "lodash", Version: "4.17.15", Paths: []string{"/srv/a/package-lock.json"}, Scope: ScopeApp},
		{Ecosystem: EcoNPM, Name: "lodash", Version: "4.17.21", Paths: []string{"/srv/c/package-lock.json"}},
	}
	out := Dedupe(in)
	if len(out) != 2 {
		t.Fatalf("got %v", out)
	}
	c := out[0]
	if c.Version != "4.17.15" || strings.Join(c.Paths, ",") != "/srv/a/package-lock.json,/srv/b/package-lock.json" || c.Dev || c.Scope != ScopeApp {
		t.Errorf("merged = %+v", c)
	}
	if in[0].Paths[0] != "/srv/b/package-lock.json" {
		t.Error("Dedupe must not modify its input")
	}
}

